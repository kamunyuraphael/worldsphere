#!/usr/bin/env node
/**
 * Refreshes attribution + properly-tracked URLs for every Unsplash photo the
 * app uses. Per Unsplash's API Guidelines this deliberately does NOT rehost
 * these photos anywhere (not even Cloudinary):
 *
 *   "All API uses must use the hotlinked image URLs returned by the API
 *   under the photo.urls properties... For companies that need to use their
 *   own image infrastructure to host the images, contact our API team."
 *   — help.unsplash.com/api-guidelines/more-on-each-guideline/guideline-hotlinking-images
 *
 * So this script:
 *   1. Calls GET /photos/:id for each photo ID already used in the app
 *      (extracted below — these are the exact photos already chosen, this
 *      just fetches them properly through the API instead of a hand-copied
 *      URL with no ixid/attribution).
 *   2. Triggers the required download-tracking ping (links.download_location)
 *      — required once per "use" of a photo, per the "Triggering a download"
 *      guideline. Re-running this script re-triggers it; that's expected and
 *      fine — it's only meant to not fire on e.g. every page view.
 *   3. Writes src/data/unsplashCredits.generated.ts: id -> { url (with ixid
 *      preserved), name, profileUrl }, for <UnsplashCredit> to render.
 *
 * Usage:
 *   node scripts/refresh-unsplash-credits.mjs            # dry run (default)
 *   node scripts/refresh-unsplash-credits.mjs --apply    # hits the real API
 *
 * Required env: UNSPLASH_ACCESS_KEY, APP_NAME (for the required utm_source)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const APPLY = process.argv.includes('--apply');
const OUT_PATH = path.join(ROOT, 'src/data/unsplashCredits.generated.ts');

// The exact photos already chosen and in use across Home.tsx, Tourism.tsx and
// destinationGuides.ts (nairobi and city share one photo). Add a new entry
// here (key + Unsplash photo ID) any time a new Unsplash photo is chosen,
// then re-run this script — don't hand-edit the generated output file.
const PHOTOS = {
  'africa': '1516426122078-c23e76319801',
  'asia': '1528360983277-13d401cdc186',
  'europe': '1470770841072-f978cf4d019e',
  'north-america': '1500530855697-b586d89ba3ee',
  'south-america': '1526392060635-9d6019884377',
  'oceania': '1507525428034-b723cf961d3e',
  'nairobi': '1741991110666-88115e724741',
};

async function fetchPhoto(id, accessKey) {
  const res = await fetch(`https://api.unsplash.com/photos/${id}`, {
    headers: { Authorization: `Client-ID ${accessKey}` },
  });
  if (!res.ok) throw new Error(`Unsplash GET /photos/${id} failed: ${res.status} ${await res.text()}`);
  return res.json();
}

async function triggerDownload(downloadLocation, accessKey) {
  const url = new URL(downloadLocation);
  url.searchParams.set('client_id', accessKey);
  const res = await fetch(url, { headers: { Authorization: `Client-ID ${accessKey}` } });
  if (!res.ok) throw new Error(`Unsplash download-tracking ping failed: ${res.status} ${await res.text()}`);
}

export function displayUrl(rawUrl, { w, q = 84 } = {}) {
  const url = new URL(rawUrl); // urls.raw already carries ixid — every param added below preserves it, never strips it
  url.searchParams.set('auto', 'format');
  url.searchParams.set('fit', 'crop');
  if (w) url.searchParams.set('w', String(w));
  url.searchParams.set('q', String(q));
  return url.toString();
}

export function renderOutputFile(entries, appName) {
  const lines = Object.entries(entries).map(([key, v]) =>
    `  ${JSON.stringify(key)}: { url: ${JSON.stringify(v.url)}, name: ${JSON.stringify(v.name)}, profileUrl: ${JSON.stringify(`${v.profileUrl}?utm_source=${appName}&utm_medium=referral`)}, photoPage: ${JSON.stringify(`${v.photoPage}?utm_source=${appName}&utm_medium=referral`)} },`,
  );
  return `/* Generated by scripts/refresh-unsplash-credits.mjs. Do not hand-edit — add a
 * new photo to the PHOTOS map in that script and re-run it instead.
 *
 * These are hotlinked Unsplash CDN URLs (images.unsplash.com), never
 * rehosted, per Unsplash's API Guidelines. */
export type UnsplashCredit = { url: string; name: string; profileUrl: string; photoPage: string };

export const unsplashCredits: Record<string, UnsplashCredit> = {
${lines.join('\n')}
};
`;
}

async function main() {
  const accessKey = process.env.UNSPLASH_ACCESS_KEY;
  const appName = process.env.APP_NAME || 'worldsphere';

  if (!APPLY) {
    console.log('DRY RUN — no network calls, no files written. Pass --apply to actually refresh.\n');
    console.log(`Would fetch ${Object.keys(PHOTOS).length} photos and trigger a download ping for each:`);
    for (const [key, id] of Object.entries(PHOTOS)) console.log(`  ${key.padEnd(14)} photo-${id}`);
    console.log(`\nWould write ${path.relative(ROOT, OUT_PATH)}`);
    return;
  }

  if (!accessKey) throw new Error('UNSPLASH_ACCESS_KEY must be set to --apply.');

  const entries = {};
  for (const [key, id] of Object.entries(PHOTOS)) {
    process.stdout.write(`Fetching ${key} (photo-${id}) ... `);
    const photo = await fetchPhoto(id, accessKey);
    await triggerDownload(photo.links.download_location, accessKey);
    entries[key] = {
      url: displayUrl(photo.urls.raw, { w: key === 'nairobi' ? 1400 : 1200 }),
      name: photo.user.name,
      profileUrl: photo.user.links.html,
      photoPage: photo.links.html,
    };
    console.log(`ok (credit: ${photo.user.name})`);
  }

  fs.writeFileSync(OUT_PATH, renderOutputFile(entries, appName));
  console.log(`\nWrote ${path.relative(ROOT, OUT_PATH)}`);
}

main().catch((err) => { console.error(err); process.exitCode = 1; });
